import { glyph, markGroup, markSvg, wordmark } from "./geometry.js";
import { identities } from "./identities.js";
import { glyphs, type Glyph, type MarkPaths } from "./model.js";
import { palette, typography } from "./tokens.js";

/**
 * Web-facing exports: mark geometry for inline SVG, standalone mark files and
 * the colour tokens as CSS custom properties.
 */
export function markData(): { wordmark: MarkPaths; glyphs: Record<Glyph, MarkPaths> } {
  return {
    wordmark: wordmark(),
    glyphs: Object.fromEntries(glyphs.map((name) => [name, glyph(name)])) as Record<Glyph, MarkPaths>,
  };
}

export function webMarkFiles(): Record<string, string> {
  const files: Record<string, string> = {
    "wordmark.svg": markSvg(wordmark(), palette.light, "Runic"),
    "wordmark-dark.svg": markSvg(wordmark(), palette.dark, "Runic"),
  };
  for (const identity of identities) {
    files[`${identity.id}.svg`] = markSvg(glyph(identity.glyph), palette.light, identity.name);
    files[`${identity.id}-dark.svg`] = markSvg(glyph(identity.glyph), palette.dark, identity.name);
  }
  return files;
}

/** A favicon: the glyph on a rounded basalt tile. */
export function faviconSvg(name: Glyph): string {
  const mark = glyph(name);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" fill="${palette.dark.raised}"/>${markGroup(mark, palette.dark, { x: 5, y: 5, scale: 0.22 })}</svg>\n`;
}

export function tokensCss(): string {
  const scheme = (values: Record<string, string>, indent: string) =>
    Object.entries(values)
      .map(([name, value]) => `${indent}--rune-${name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}: ${value};`)
      .join("\n");
  return `/* Generated by @runic-artifex/brand. Change src/tokens.ts and run npm run generate. */
:root {
${scheme(palette.light, "  ")}
  --rune-font-sans:
    '${typography.sans} Variable', '${typography.sans}', system-ui, sans-serif;
  --rune-font-mono:
    '${typography.mono} Variable', '${typography.mono}', ui-monospace, monospace;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-scheme='light']) {
${scheme(palette.dark, "    ")}
  }
}

:root[data-scheme='dark'] {
${scheme(palette.dark, "  ")}
}
`;
}
